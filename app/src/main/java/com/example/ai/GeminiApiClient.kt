package com.example.ai

import android.util.Log
import com.example.BuildConfig
import com.example.model.Language
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONArray
import org.json.JSONObject
import java.io.IOException
import java.util.concurrent.TimeUnit

class GeminiApiClient {

    private val client = OkHttpClient.Builder()
        .connectTimeout(25, TimeUnit.SECONDS)
        .readTimeout(35, TimeUnit.SECONDS)
        .writeTimeout(25, TimeUnit.SECONDS)
        .build()

    private val jsonMediaType = "application/json; charset=utf-8".toMediaType()

    suspend fun generateResponse(
        userPrompt: String,
        language: Language,
        customApiKey: String?,
        modelName: String = "gemini-2.0-flash"
    ): Result<String> = withContext(Dispatchers.IO) {
        val apiKey = resolveApiKey(customApiKey)
        if (apiKey.isNullOrBlank() || apiKey == "MY_GEMINI_API_KEY") {
            val keyMissingMessage = when (language) {
                Language.BENGALI -> "Gemini API key সেট করা নেই। দয়া করে উপরে সেটিংস আইকনে ট্যাপ করে আপনার API কী লিখুন।"
                Language.HINDI -> "Gemini API key सेट नहीं है। कृपया ऊपर सेटिंग्स आइकन पर टैप करके अपनी API key दर्ज करें।"
                Language.ENGLISH -> "Gemini API key is not configured. Please tap the Settings icon in the top bar to set your Gemini API key."
            }
            return@withContext Result.failure(IllegalStateException(keyMissingMessage))
        }

        val systemPersona = when (language) {
            Language.BENGALI -> "তুমি JARVIS AI, একজন অত্যন্ত বুদ্ধিমান, অনুগত এবং সহায়ক ব্যক্তিগত সহকারী। উত্তরে আসগর বাবুকে সম্মান দিয়ে সহজ, স্পষ্ট ও সংক্ষিপ্ত কথা বলবে। অপ্রয়োজনীয় বড় বাক্য পরিহার করবে।"
            Language.HINDI -> "आप JARVIS AI हैं, एक अत्यधिक बुद्धिमान और विनम्र वॉयस असिस्टेंट। उत्तर संक्षिप्त, स्पष्ट और बातचीत की शैली में दें।"
            Language.ENGLISH -> "You are JARVIS AI, an intelligent, respectful, and polite voice assistant. Keep answers natural, concise, and suitable for text-to-speech reading. Do not use markdown bullet lists or excessive asterisks."
        }

        val requestPayload = JSONObject().apply {
            val contentsArray = JSONArray().apply {
                put(JSONObject().apply {
                    put("role", "user")
                    put("parts", JSONArray().apply {
                        put(JSONObject().put("text", userPrompt))
                    })
                })
            }
            put("contents", contentsArray)

            put("systemInstruction", JSONObject().apply {
                put("parts", JSONArray().apply {
                    put(JSONObject().put("text", systemPersona))
                })
            })

            put("generationConfig", JSONObject().apply {
                put("temperature", 0.7)
                put("maxOutputTokens", 512)
            })
        }

        val targetModel = if (modelName.isNotBlank()) modelName else "gemini-2.0-flash"
        val url = "https://generativelanguage.googleapis.com/v1beta/models/$targetModel:generateContent?key=$apiKey"

        val request = Request.Builder()
            .url(url)
            .post(requestPayload.toString().toRequestBody(jsonMediaType))
            .build()

        try {
            client.newCall(request).execute().use { response ->
                val body = response.body?.string()
                if (!response.isSuccessful || body.isNullOrBlank()) {
                    val errorDetail = parseErrorMessage(body) ?: "HTTP Error ${response.code}: ${response.message}"
                    Log.e(TAG, "Gemini API call failed: $errorDetail")
                    return@withContext Result.failure(IOException(errorDetail))
                }

                val jsonResponse = JSONObject(body)
                val candidates = jsonResponse.optJSONArray("candidates")
                if (candidates == null || candidates.length() == 0) {
                    return@withContext Result.failure(IOException("No response generated by Gemini model."))
                }

                val firstCandidate = candidates.getJSONObject(0)
                val content = firstCandidate.optJSONObject("content")
                val parts = content?.optJSONArray("parts")
                val rawText = if (parts != null && parts.length() > 0) {
                    parts.getJSONObject(0).optString("text", "")
                } else {
                    ""
                }

                if (rawText.isBlank()) {
                    return@withContext Result.failure(IOException("Empty response received from model."))
                }

                val cleanedText = cleanForSpeech(rawText)
                Result.success(cleanedText)
            }
        } catch (e: Exception) {
            Log.e(TAG, "Exception contacting Gemini API", e)
            val friendlyError = when {
                e is java.net.UnknownHostException -> "No internet connection. Please check your network."
                e.message?.contains("API_KEY_INVALID", ignoreCase = true) == true -> "The provided Gemini API key is invalid. Please verify in Settings."
                e.message?.contains("RESOURCE_EXHAUSTED", ignoreCase = true) == true -> "Gemini API quota exceeded. Please check your API account."
                else -> e.message ?: "Failed to reach Gemini AI service."
            }
            Result.failure(IOException(friendlyError))
        }
    }

    private fun resolveApiKey(customApiKey: String?): String? {
        if (!customApiKey.isNullOrBlank()) {
            return customApiKey.trim()
        }
        val buildKey = try {
            BuildConfig::class.java.getField("GEMINI_API_KEY").get(null) as? String
        } catch (e: Exception) {
            null
        }
        return buildKey?.trim()
    }

    private fun parseErrorMessage(body: String?): String? {
        if (body.isNullOrBlank()) return null
        return try {
            val json = JSONObject(body)
            val error = json.optJSONObject("error")
            error?.optString("message")
        } catch (e: Exception) {
            null
        }
    }

    private fun cleanForSpeech(text: String): String {
        return text
            .replace(Regex("\\*\\*(.*?)\\*\\*"), "$1") // strip bold markdown
            .replace(Regex("\\*(.*?)\\*"), "$1") // strip italic markdown
            .replace(Regex("`{1,3}.*?`{1,3}"), "") // strip code snippets
            .replace(Regex("[#*_~>]+"), "")
            .replace(Regex("\\n{2,}"), "\n")
            .trim()
    }

    companion object {
        private const val TAG = "GeminiApiClient"
    }
}
